    def explain_term(self, term):
        """Возвращает карточку термина или None"""
        return self.cards.get(term.lower())

    def explain_deal(self, trade, term):
        """Формирует объяснение сделки на основе карточки термина"""
        card = self.explain_term(term)
        if not card:
            return f"Термин '{term}' не найден в базе."

        return (
            f"Сделка #{trade['id']}: {trade['asset']} {trade['direction']}.\n"
            f"Вход: {trade['entry']}, Стоп: {trade['stop_loss']}, Тейк: {trade['take_profit']}.\n"
            f"Причина: {card['description']}\n"
            f"Как выглядит: {card['visual']}\n"
            f"Сигнал: {card['signal']}"
        )

    def list_terms(self):
        """Список всех доступных терминов"""
        return list(self.cards.keys())


